CREATE TABLE IF NOT EXISTS field_semantic_candidates (
    id BIGSERIAL PRIMARY KEY,
    field_id BIGINT NOT NULL REFERENCES arcgis_fields(id),
    semantic_role_id BIGINT NOT NULL REFERENCES semantic_roles(id),
    similarity_score NUMERIC NOT NULL,
    rank INTEGER NOT NULL,
    method TEXT DEFAULT 'embedding',
    created_at TIMESTAMP DEFAULT NOW(),
    UNIQUE (field_id, semantic_role_id)
);
