CREATE EXTENSION IF NOT EXISTS vector;

CREATE TABLE IF NOT EXISTS semantic_roles (
    id BIGSERIAL PRIMARY KEY,
    role_name TEXT NOT NULL UNIQUE,
    description TEXT,
    category TEXT,
    parent_role_id BIGINT REFERENCES semantic_roles(id),
    embedding_model TEXT,
    embedding_vector vector(1536),
    aliases JSONB DEFAULT '[]'::jsonb,
    keywords JSONB DEFAULT '[]'::jsonb,
    is_active BOOLEAN DEFAULT TRUE,
    created_at TIMESTAMP DEFAULT NOW(),
    updated_at TIMESTAMP DEFAULT NOW()
);

CREATE INDEX idx_semantic_roles_role_name ON semantic_roles(role_name);
CREATE INDEX idx_semantic_roles_category ON semantic_roles(category);
CREATE INDEX idx_semantic_roles_aliases ON semantic_roles USING GIN (aliases);
CREATE INDEX idx_semantic_roles_keywords ON semantic_roles USING GIN (keywords);

